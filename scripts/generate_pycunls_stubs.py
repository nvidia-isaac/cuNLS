"""Regenerates the type stubs of pycunls: _pycunls_core.pyi and _vectors.pyi.

_pycunls_core.pyi comes from the built extension (nanobind stubgen): the binding docstrings are
the single source. _vectors.pyi declares the numbered vector names (VectorStateBatch3, ...),
which pycunls/_vectors.py creates at run time where type checkers cannot see them. Run it after
changing a binding or the numbered names, with a Python that imports the freshly built pycunls:

    python scripts/generate_pycunls_stubs.py [--stubgen PATH/TO/nanobind/src/stubgen.py]

Without --stubgen it uses `python -m nanobind.stubgen` (pip install nanobind).
"""

import argparse
import pathlib
import re
import subprocess
import sys
import tempfile

REPO = pathlib.Path(__file__).resolve().parents[1]
STUB = REPO / "python" / "pycunls" / "_pycunls_core.pyi"
VECTORS_STUB = REPO / "python" / "pycunls" / "_vectors.pyi"
